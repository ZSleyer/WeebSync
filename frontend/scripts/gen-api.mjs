// Generates src/api.gen.ts from the backend's OpenAPI spec: one Schemas
// interface keyed by schema name ('api.User'), which api.ts aliases.
//
// openapi-typescript needs the TypeScript 5 compiler API, which TypeScript 7
// no longer ships, and the spec only uses a handful of keywords. Anything
// outside that set throws, so a new shape in the spec fails `yarn gen:api`
// instead of turning into `unknown` in the frontend.
//
// Usage: yarn gen:api

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const REF = '#/components/schemas/'
const PRIMITIVES = { string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' }
// keywords that carry no type information
const IGNORED = new Set(['description', 'example', 'uniqueItems', 'x-enum-varnames', 'x-enum-comments'])
const KNOWN = new Set([
  ...IGNORED,
  'type',
  'properties',
  'required',
  'items',
  '$ref',
  'additionalProperties',
  'enum',
  'anyOf',
])

export function generate(spec) {
  const schemas = spec.components?.schemas ?? {}
  const lines = [
    '// Generated by scripts/gen-api.mjs from backend/docs/swagger.json. Do not edit;',
    '// run `yarn gen:api` after backend/gen-docs.sh.',
    '',
    'export interface Schemas {',
  ]
  for (const name of Object.keys(schemas).toSorted()) {
    lines.push(...doc(schemas[name], '  '), `  ${quote(name)}: ${type(schemas[name], '  ', name)}`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

function type(s, indent, where) {
  const unknownKey = Object.keys(s).find((k) => !KNOWN.has(k))
  if (unknownKey) throw new Error(`${where}: unsupported keyword ${unknownKey}`)

  if (s.$ref) {
    if (!s.$ref.startsWith(REF)) throw new Error(`${where}: unsupported $ref ${s.$ref}`)
    return `Schemas[${quote(s.$ref.slice(REF.length))}]`
  }
  if (s.anyOf) return s.anyOf.map((v, i) => type(v, indent, `${where}.anyOf[${i}]`)).join(' | ')
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
  // an empty schema is a Go `any` field
  if (Object.keys(s).every((k) => IGNORED.has(k))) return 'unknown'

  const types = Array.isArray(s.type) ? s.type : [s.type]
  return types.map((t) => single(t, s, indent, where)).join(' | ')
}

function single(t, s, indent, where) {
  if (t in PRIMITIVES) return PRIMITIVES[t]
  if (t === 'array') {
    if (!s.items) throw new Error(`${where}: array without items`)
    const item = type(s.items, indent, `${where}[]`)
    return item.includes('|') ? `(${item})[]` : `${item}[]`
  }
  if (t !== 'object') throw new Error(`${where}: unsupported type ${t}`)

  if (s.properties) {
    if (s.additionalProperties) throw new Error(`${where}: properties and additionalProperties`)
    const required = new Set(s.required ?? [])
    const inner = `${indent}  `
    const props = Object.keys(s.properties)
      .toSorted()
      .flatMap((p) => [
        ...doc(s.properties[p], inner),
        `${inner}${quote(p)}${required.has(p) ? '' : '?'}: ${type(s.properties[p], inner, `${where}.${p}`)}`,
      ])
    return `{\n${props.join('\n')}\n${indent}}`
  }
  if (typeof s.additionalProperties === 'object' && Object.keys(s.additionalProperties).length > 0) {
    // a Go map promises no key, so a lookup may come back undefined
    return `Partial<Record<string, ${type(s.additionalProperties, indent, `${where}{}`)}>>`
  }
  // a free-form object swag could not look into (a third-party type)
  return 'Record<string, unknown>'
}

function doc(s, indent) {
  if (!s.description) return []
  const text = s.description.replaceAll('*/', '*\\/').split('\n')
  return [`${indent}/**`, ...text.map((l) => `${indent} *${l ? ` ${l}` : ''}`), `${indent} */`]
}

function quote(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('..', import.meta.url)
  const spec = JSON.parse(readFileSync(new URL('../backend/docs/swagger.json', root), 'utf8'))
  writeFileSync(new URL('src/api.gen.ts', root), generate(spec))
}
