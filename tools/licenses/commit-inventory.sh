#!/bin/bash
# CI on main: commits a regenerated license inventory back to main, so the
# image built right after ships the notices of what it bundles. Run after
# generate.sh in a checkout of $HEAD_SHA.
#
# The commit goes through GitHub's createCommitOnBranch, so GitHub signs it,
# and expectedHeadOid makes it fail instead of overwriting a newer main. A
# push made with GITHUB_TOKEN starts no new workflow run, so this does not
# loop. Writes sha=<the commit to build> to $GITHUB_OUTPUT.
#
# Env: GH_TOKEN (contents: write), REPO (owner/name), HEAD_SHA.
set -euo pipefail

files=(frontend/src/licenses/inventory.json frontend/src/licenses/texts.json)

# A newer push to main has its own run, which regenerates and builds that
# state: this one stands down (empty sha, dev-image skips) instead of failing.
superseded() {
  echo "::notice::main moved on past $HEAD_SHA; the newer run commits the inventory and builds the image"
  echo "sha=" >>"$GITHUB_OUTPUT"
  exit 0
}
[ "$(gh api "repos/$REPO/commits/main" --jq .sha)" = "$HEAD_SHA" ] || superseded

if git diff --quiet -- "${files[@]}"; then
  echo "license inventory up to date"
  echo "sha=$HEAD_SHA" >>"$GITHUB_OUTPUT"
  exit 0
fi
git diff --stat -- "${files[@]}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
payload="$work/payload.json"
# the contents go through files: texts.json in base64 is far over the
# 128 KiB a single command-line argument may hold
for f in "${files[@]}"; do
  base64 -w0 "$f" >"$work/b64"
  jq -n --arg path "$f" --rawfile contents "$work/b64" '{path: $path, contents: $contents}'
done >"$work/additions"
jq -n \
  --arg repo "$REPO" \
  --arg head "$HEAD_SHA" \
  --slurpfile additions "$work/additions" \
  '{
    query: "mutation($input: CreateCommitOnBranchInput!) { createCommitOnBranch(input: $input) { commit { oid } } }",
    variables: {input: {
      branch: {repositoryNameWithOwner: $repo, branchName: "main"},
      expectedHeadOid: $head,
      message: {
        headline: "chore(licenses): update the third-party license inventory",
        body: "Regenerated by CI with tools/licenses/generate.sh after the bundle or the Go module graph changed."
      },
      fileChanges: {additions: $additions}
    }}
  }' >"$payload"

if ! oid="$(gh api graphql --input "$payload" --jq '.data.createCommitOnBranch.commit.oid' 2>"$work/err")"; then
  # expectedHeadOid no longer matches: main moved between the check and now
  [ "$(gh api "repos/$REPO/commits/main" --jq .sha)" != "$HEAD_SHA" ] && superseded
  cat "$work/err" >&2
  exit 1
fi
[ -n "$oid" ] || { echo "createCommitOnBranch returned no commit" >&2; exit 1; }
echo "committed $oid"
echo "sha=$oid" >>"$GITHUB_OUTPUT"
